#!/usr/bin/env python3
"""Embed the same static footer and stylesheet in every content page."""
from html.parser import HTMLParser
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parents[1]
CSS = '/cr-plumbing/assets/shared-footer.css?v=20261104-01'


def is_site_footer(match):
    class Attrs(HTMLParser):
        attrs = {}
        def handle_starttag(self, tag, attrs): self.attrs = dict(attrs)
    p = Attrs()
    p.feed(match[0].split('>', 1)[0]+'>')
    return 'footer' in p.attrs.get('class', '').split()


def generate(check=False):
    footer = (ROOT/'partials/site-footer.html').read_text().strip()
    link = f'<link rel="stylesheet" href="{CSS}">'
    changed = []
    count = 0
    for path in sorted(ROOT.rglob('index.html')):
        source = path.read_text()
        if re.search(r'<meta\b[^>]*http-equiv\s*=\s*["\']refresh["\']', source, re.I):
            continue
        count += 1
        matches = [m for m in re.finditer(r'<footer\b[^>]*>.*?</footer>', source, re.S | re.I) if is_site_footer(m)]
        if len(matches) != 1:
            raise ValueError(f'{path}: expected one site footer, got {len(matches)}')
        match = matches[0]
        output = source[:match.start()] + footer + source[match.end():]
        old_css = re.search(r'<link\b[^>]*href=["\'][^"\']*shared-footer\.css[^"\']*["\'][^>]*>', output, re.I)
        if old_css:
            output = output[:old_css.start()] + link + output[old_css.end():]
        else:
            anchor = '<!-- CR SEO: generated by scripts/build_seo.py -->'
            output = output.replace(anchor, link+'\n'+anchor, 1) if anchor in output else output.replace('</head>', link+'\n</head>', 1)
        # Invalidate the shared script after removing its old footer mutation.
        output = re.sub(r'(assets/site\.js)\?v=[^"\'<>\s]+', r'\1?v=20261104-footer-01', output)
        if output != source:
            changed.append(str(path.relative_to(ROOT)))
            if not check: path.write_text(output)
    print(f'Shared footer: {count} content pages, {len(changed)} {"outdated" if check else "updated"}')
    if check and changed:
        raise SystemExit('Run python3 scripts/build_footer.py: '+', '.join(changed[:8]))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
