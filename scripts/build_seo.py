class Head(HTMLParser):
    def __init__(self, source):
        super().__init__(convert_charrefs=True)
        self.tags = []
        self.in_title = False
        self.title = ''
        self.feed(source)

    def handle_starttag(self, tag, attrs):
        self.tags.append((tag, dict(attrs)))
        if tag == 'title':
            self.in_title = True

    def handle_endtag(self, tag):
        if tag == 'title':
            self.in_title = False

    def handle_data(self, data):
        if self.in_title:
            self.title += data

    def meta(self, key):
        return next((a.get('content', '') for t, a in self.tags if t == 'meta' and a.get('name', '').lower() == key), '')

    def redirect(self):
        return next((a.get('content', '').split('=', 1)[-1].strip() for t, a in self.tags if t == 'meta' and a.get('http-equiv', '').lower() == 'refresh'), None)


def clean_text(value):
    return ' '.join(unescape(value).split()).strip(' :')


def page_data(path, source):
    head = Head(re.search(r'<head\b[^>]*>(.*?)</head>', source, re.S | re.I)[1])
    route = path.parent.relative_to(ROOT).as_posix()
    route = '' if route == '.' else route + '/'
    if route in PAGES:
        core, description = PAGES[route]
    elif route.startswith('service-areas/'):
        city = re.search(r'data-city=["\']([^"\']+)', source)
        city = unescape(city[1]) if city else route.split('/')[-2].replace('-tx', '').replace('-', ' ').title()
        core = f'{city}, TX Plumbing, HVAC & Electrical'
        description = f'Explore plumbing, heating, cooling, electrical and gas services in {city}, Texas. Find local service information and contact CR Plumbing, Air & Electric.'
    else:
        core = SHORT_TITLES.get(route, clean_text(head.title.split('|')[0]))
        if not re.search(r'\b(DFW|Texas|Argyle|Fort Worth)\b', core, re.I):
            core += ' in DFW'
        description = DESCRIPTIONS.get(route, clean_text(head.meta('description')))
        if not description:
            description = f'Explore {core} with CR Plumbing, Air & Electric. Find service information and contact the team about your property and availability.'
    if len(description) > 180:
        description = description[:177].rsplit(' ', 1)[0].rstrip(' ,;:') + '…'
    return dict(path=path, source=source, route=route, title=f'{core} | {BRAND}', description=description, redirect=head.redirect())


def managed_tag(match):
    tag = match[0]
    parsed = Head(tag)
    if not parsed.tags:
        return tag
    name, a = parsed.tags[0]
    if name == 'meta':
        key = a.get('name', '').lower()
        if key in ('description', 'robots', 'theme-color', 'application-name') or key.startswith('twitter:') or a.get('property', '').lower().startswith('og:'):
            return ''
    if name == 'link' and set(a.get('rel', '').lower().split()) & {'canonical', 'icon', 'apple-touch-icon', 'manifest'}:
        return ''
    return tag


def generate(check=False):
    config = json.loads((ROOT / 'assets/seo-config.json').read_text())
    base = config['base_url']
    parsed = urlsplit(base)
    if parsed.scheme != 'https' or not parsed.netloc or not base.endswith('/') or parsed.query or parsed.fragment:
        raise ValueError('base_url must be an absolute HTTPS URL ending in /, with no query or fragment')
    if type(config['indexing_enabled']) is not bool:
        raise ValueError('indexing_enabled must be true or false')
    if config['indexing_enabled'] and parsed.hostname == 'atrezzostudiosv-spec.github.io':
        raise ValueError('The client-review GitHub Pages host must stay noindex. Set the confirmed production domain first.')
    pages = [page_data(p, p.read_text()) for p in sorted(ROOT.rglob('index.html')) if '.git' not in p.parts]
    by_route = {p['route']: p for p in pages}
    duplicates = [title for title, n in Counter(p['title'] for p in pages if not p['redirect']).items() if n > 1]
    if duplicates:
        raise ValueError(f'Duplicate page titles: {duplicates}')
    changes = []
    for page in pages:
        route, source = page['route'], page['source']
        target = (page['redirect'] or '').removeprefix('/cr-plumbing/')
        canonical = urljoin(base, target) if page['redirect'] else base + route
        title, description = page['title'], page['description']
        robots = 'index,follow,max-image-preview:large' if config['indexing_enabled'] and not page['redirect'] else 'noindex,nofollow'
        image = urljoin(base, config['social_image'])
        tags = [START, f'<title>{escape(title)}</title>']
        def meta(name, value, prop=False):
            tags.append(f'<meta {"property" if prop else "name"}="{name}" content="{escape(str(value), quote=True)}">')
        meta('description', description)
        meta('robots', robots)
        meta('theme-color', '#102532')
        meta('application-name', config['site_name'])
        tags.append(f'<link rel="canonical" href="{escape(canonical, quote=True)}">')
        for key, value in [('og:type', 'website'), ('og:site_name', config['site_name']), ('og:locale', 'en_US'), ('og:title', title), ('og:description', description), ('og:url', canonical), ('og:image', image), ('og:image:secure_url', image), ('og:image:type', 'image/jpeg'), ('og:image:width', 1200), ('og:image:height', 630), ('og:image:alt', config['social_image_alt'])]:
            meta(key, value, True)
        for key, value in [('twitter:card', 'summary_large_image'), ('twitter:title', title), ('twitter:description', description), ('twitter:image', image), ('twitter:image:alt', config['social_image_alt'])]:
            meta(key, value)
        for rel, file, extra in [('icon', 'favicon.ico', ' type="image/x-icon" sizes="32x32 48x48"'), ('icon', 'assets/brand/favicon-48.png', ' type="image/png" sizes="48x48"'), ('apple-touch-icon', 'assets/brand/apple-touch-icon.png', ' sizes="180x180"'), ('manifest', 'site.webmanifest', '')]:
            tags.append(f'<link rel="{rel}" href="{urljoin(base, file)}"{extra}>')
        if not page['redirect']:
            crumbs = [{'@type': 'ListItem', 'position': 1, 'name': 'Home', 'item': base}]
            pieces = route.strip('/').split('/') if route else []
            for i in range(len(pieces)):
                parent_route = '/'.join(pieces[:i+1]) + '/'
                parent = by_route.get(parent_route)
                if parent:
                    crumbs.append({'@type': 'ListItem', 'position': len(crumbs)+1, 'name': parent['title'].rsplit(' | ', 1)[0], 'item': base+parent_route})
            graph = [
                {'@type': 'Organization', '@id': base+'#organization', 'name': config['site_name'], 'url': base, 'logo': urljoin(base, config['logo'])},
                {'@type': 'WebSite', '@id': base+'#website', 'name': config['site_name'], 'url': base, 'inLanguage': 'en-US', 'publisher': {'@id': base+'#organization'}},
                {'@type': 'WebPage', '@id': canonical+'#webpage', 'url': canonical, 'name': title, 'description': description, 'inLanguage': 'en-US', 'isPartOf': {'@id': base+'#website'}, 'breadcrumb': {'@id': canonical+'#breadcrumb'}, 'primaryImageOfPage': {'@type': 'ImageObject', 'url': image, 'width': 1200, 'height': 630}},
                {'@type': 'BreadcrumbList', '@id': canonical+'#breadcrumb', 'itemListElement': crumbs},
            ]
            payload = json.dumps({'@context': 'https://schema.org', '@graph': graph}, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c')
            tags.append(f'<script type="application/ld+json" id="cr-seo-schema">{payload}</script>')
        tags.append(END)
        block = '\n'.join(tags)
        match = re.search(r'(<head\b[^>]*>)(.*?)(</head>)', source, re.S | re.I)
        head = re.sub(re.escape(START)+r'.*?'+re.escape(END), '', match[2], flags=re.S)
        head = re.sub(r'<title\b[^>]*>.*?</title>', '', head, flags=re.S | re.I)
        head = re.sub(r'<(?:meta|link)\b[^>]*>', managed_tag, head, flags=re.I)
        # Existing document body remains byte-for-byte intact.
        output = source[:match.start()] + match[1] + head.rstrip() + '\n' + block + '\n' + match[3] + source[match.end():]
        if output != source:
            changes.append(str(page['path'].relative_to(ROOT)))
            if not check:
                page['path'].write_text(output)
    ns = 'http://www.sitemaps.org/schemas/sitemap/0.9'
    ET.register_namespace('', ns)
    sitemap = ET.Element(f'{{{ns}}}urlset')
    if config['indexing_enabled']:
        for page in pages:
            if not page['redirect']:
                url = ET.SubElement(sitemap, f'{{{ns}}}url')
                ET.SubElement(url, f'{{{ns}}}loc').text = base + page['route']
    assets = {
        'sitemap.xml': '<?xml version="1.0" encoding="UTF-8"?>\n'+ET.tostring(sitemap, encoding='unicode')+'\n',
        'site.webmanifest': json.dumps({'id': base, 'name': config['site_name'], 'short_name': 'CR Plumbing', 'start_url': base, 'scope': base, 'display': 'browser', 'background_color': '#ffffff', 'theme_color': '#102532', 'icons': [{'src': urljoin(base, f'assets/brand/icon-{size}.png'), 'sizes': f'{size}x{size}', 'type': 'image/png', 'purpose': 'any'} for size in (192, 512)]}, indent=2)+'\n',
    }
    for name, content in assets.items():
        path = ROOT / name
        if not path.exists() or path.read_text() != content:
            changes.append(name)
            if not check:
                path.write_text(content)
    print(f'SEO: {len(pages)} routes; {sum(not p["redirect"] for p in pages)} content pages; indexing={config["indexing_enabled"]}; {len(changes)} {"outdated files" if check else "files updated"}')
    if check and changes:
        raise SystemExit('Run python3 scripts/build_seo.py; generated SEO is stale: '+', '.join(changes[:8]))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated metadata differs, without writing files')
    generate(parser.parse_args().check)
